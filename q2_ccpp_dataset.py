class ANN_1:
    def __init__(self, learning_rate=0.01, regularization_lambda=0.1, beta1=0.9, beta2=0.999, epsilon=1e-8):
        self.learning_rate = learning_rate  # Adjustable learning rate
        self.lambda_l2 = regularization_lambda  # L2 Regularization parameter
        self.beta1 = beta1  # Exponential decay rate for first moment estimates
        self.beta2 = beta2  # Exponential decay rate for second moment estimates
        self.epsilon = epsilon  # Small value to prevent division by zero

        # Initialize moment estimates
        self.m = {}  # First moment (mean)
        self.v = {}  # Second moment (variance)
        self.t = 0  # Timestep

        self.layers = []
        self.params = {}
        self.cache = {}
        self.grads = {}

    # Add a layer with appropriate initialization
    def add_layer(self, input_size, output_size, activation='relu'):
        layer_num = len(self.layers) + 1

        if activation == 'relu':
            # He Initialization
            std = np.sqrt(2. / input_size)
        elif activation in ['sigmoid', 'tanh']:
            # Xavier Initialization
            std = np.sqrt(1. / input_size)
        elif activation == 'linear':
            std = np.sqrt(1. / input_size)  # Similar to Xavier
        else:
            raise Exception(f"Unsupported activation: {activation}")

        # Initialize weights and biases
        self.params[f'W{layer_num}'] = np.random.randn(output_size, input_size) * std
        self.params[f'b{layer_num}'] = np.zeros((output_size, 1))
        self.layers.append({
            'input_size': input_size,
            'output_size': output_size,
            'activation': activation
        })

    # ReLU Activation
    def relu(self, Z):
        return np.maximum(0, Z)

    def relu_derivative(self, Z):
        return (Z > 0).astype(float)

    # Sigmoid Activation
    def sigmoid(self, Z):
        return 1 / (1 + np.exp(-Z))

    def sigmoid_derivative(self, Z):
        sig = self.sigmoid(Z)
        return sig * (1 - sig)

    # Tanh Activation
    def tanh(self, Z):
        return np.tanh(Z)

    def tanh_derivative(self, Z):
        return 1 - np.tanh(Z) ** 2

    def add_dropout_layer(self, input_size, rate=0.5):
      self.layers.append({
        'input_size': input_size,
        'output_size': input_size,  # Same input and output size for dropout
        'activation': 'dropout',
        'rate': rate  # Dropout rate
    })

    def dropout(self, A, rate):
      # Generate a random dropout mask
      D = np.random.rand(*A.shape) > rate
      A_dropped = np.multiply(A, D) / (1 - rate)
      return A_dropped

    # Forward Propagation
    def forward(self, X):
        A = X
        self.cache['A0'] = X

        for i, layer in enumerate(self.layers):
            layer_num = i + 1
            if layer['activation'] == 'dropout':
              A = self.dropout(A, layer['rate'])
            else:
              W = self.params[f'W{layer_num}']
              b = self.params[f'b{layer_num}']
              Z = np.dot(W, A) + b
              self.cache[f'Z{layer_num}'] = Z

              if layer['activation'] == 'relu':
                  A = self.relu(Z)
              elif layer['activation'] == 'sigmoid':
                  A = self.sigmoid(Z)
              elif layer['activation'] == 'linear':
                  A = Z  # Linear for regression
              elif layer['activation'] == 'tanh':
                  A = self.tanh(Z)
              else:
                  raise Exception(f"Unsupported activation: {layer['activation']}")

              self.cache[f'A{layer_num}'] = A

        return A

    # Loss function with L2 Regularization
    def compute_loss(self, Y_pred, Y_true):
        m = Y_true.shape[1]
        mse_loss = (1 / (2 * m)) * np.sum((Y_pred - Y_true) ** 2)

        # L2 regularization term
        l2_reg_loss = 0
        for i in range(1, len(self.layers) + 1):
            W = self.params[f'W{i}']
            l2_reg_loss += np.sum(np.square(W))

        l2_reg_loss = (self.lambda_l2 / (2 * m)) * l2_reg_loss
        total_loss = mse_loss + l2_reg_loss

        return total_loss

    # Backward Propagation with L2 Regularization
    def backward(self, Y_true):
        m = Y_true.shape[1]
        L = len(self.layers)
        Y_pred = self.cache[f'A{L}']

        # Initialize the gradient
        dA = Y_pred - Y_true  # Derivative of MSE loss with respect to A_L

        for i in reversed(range(1, L + 1)):
            Z = self.cache[f'Z{i}']
            A_prev = self.cache[f'A{i-1}']
            W = self.params[f'W{i}']

            layer = self.layers[i-1]
            activation = layer['activation']

            if activation == 'relu':
                dZ = dA * self.relu_derivative(Z)
            elif activation == 'sigmoid':
                dZ = dA * self.sigmoid_derivative(Z)
            elif activation == 'linear':
                dZ = dA  # Derivative of linear activation is 1
            elif activation == 'tanh':
                dZ = dA * self.tanh_derivative(Z)
            else:
                raise Exception(f"Unsupported activation: {activation}")

            dW = (1 / m) * np.dot(dZ, A_prev.T) + (self.lambda_l2 / m) * W  # L2 regularization
            db = (1 / m) * np.sum(dZ, axis=1, keepdims=True)
            dA = np.dot(W.T, dZ)

            self.grads[f'dW{i}'] = dW
            self.grads[f'db{i}'] = db

    # Update Parameters using Gradient Descent with adjustable learning rate and L2 Regularization
    def update_parameters(self):
        self.t += 1  # Increment timestep

        L = len(self.layers)

        for i in range(1, L + 1):
            # Initialize m and v if they don't exist for the layer
            if f'm{i}' not in self.m:
                self.m[f'm{i}'] = np.zeros_like(self.params[f'W{i}'])
                self.v[f'v{i}'] = np.zeros_like(self.params[f'W{i}'])

            # Update the first moment estimate
            self.m[f'm{i}'] = self.beta1 * self.m[f'm{i}'] + (1 - self.beta1) * self.grads[f'dW{i}']
            self.v[f'v{i}'] = self.beta2 * self.v[f'v{i}'] + (1 - self.beta2) * np.square(self.grads[f'dW{i}'])

            # Bias correction
            m_hat = self.m[f'm{i}'] / (1 - self.beta1 ** self.t)
            v_hat = self.v[f'v{i}'] / (1 - self.beta2 ** self.t)

            # Update weights and biases
            self.params[f'W{i}'] -= self.learning_rate * m_hat / (np.sqrt(v_hat) + self.epsilon)
            self.params[f'b{i}'] -= self.learning_rate * self.grads[f'db{i}']

    def train(self, X, Y, epochs=10000, print_loss=True):
      loss_history = []
      initial_lr = self.learning_rate

      for epoch in range(1, epochs + 1):
          Y_pred = self.forward(X)
          loss = self.compute_loss(Y_pred, Y)
          loss_history.append(loss)

          self.backward(Y)
          self.update_parameters()

          # Implement a more dynamic learning rate decay
          self.learning_rate = initial_lr * (1 / (1 + 0.001 * epoch))

          if print_loss and epoch % 1000 == 0:
              print(f"Epoch {epoch}, Loss: {loss}")

      return loss_history

    # Prediction
    def predict(self, X):
        return self.forward(X)

# Function to create mini-batches
def create_mini_batches(X, Y, batch_size):
    # Shuffle the data at the beginning of each epoch
    m = X.shape[0]  # Number of examples
    permutation = np.random.permutation(m)
    X_shuffled = X[permutation, :]  # Shuffle X along rows
    Y_shuffled = Y[permutation].reshape(m, 1)  # Shuffle Y and reshape to (m, 1)

    mini_batches = []

    # Create mini-batches
    num_complete_batches = m // batch_size
    for k in range(num_complete_batches):
        X_mini_batch = X_shuffled[k * batch_size:(k + 1) * batch_size, :]
        Y_mini_batch = Y_shuffled[k * batch_size:(k + 1) * batch_size, :]
        mini_batches.append((X_mini_batch.T, Y_mini_batch.T))  # Transpose to match your ANN

    # Handle the remaining examples if any
    if m % batch_size != 0:
        X_mini_batch = X_shuffled[num_complete_batches * batch_size:, :]
        Y_mini_batch = Y_shuffled[num_complete_batches * batch_size:, :]
        mini_batches.append((X_mini_batch.T, Y_mini_batch.T))  # Transpose to match your ANN

    return mini_batches

# Function to train with mini-batches
def train_with_mini_batches_and_validation(ann, X_train, y_train, X_val, y_val, epochs, learning_rate, batch_size, reg_lambda, patience, print_loss=True):
    ann.learning_rate = learning_rate
    ann.regularization_lambda = reg_lambda
    print(f"\nTraining with batch size: {batch_size}")
    train_loss_history = []
    val_loss_history = []
    last_val_pred = None

    best_val_loss = float('inf')
    patience_counter = 0


    for epoch in range(1, epochs + 1):
        # Create mini-batches for training
        mini_batches = create_mini_batches(X_train, y_train, batch_size)
        epoch_train_loss = 0

        # Training process for each mini-batch
        for mini_batch_X, mini_batch_Y in mini_batches:
            # Forward and backward pass for each mini-batch
            Y_pred = ann.forward(mini_batch_X)
            loss = ann.compute_loss(Y_pred, mini_batch_Y)
            epoch_train_loss += loss

            ann.backward(mini_batch_Y)
            ann.update_parameters()

        # Store the training loss at the end of each epoch
        avg_train_loss = epoch_train_loss / len(mini_batches)
        train_loss_history.append(avg_train_loss)

        # Calculate validation loss after every epoch
        val_pred = ann.forward(X_val)

        val_loss = ann.compute_loss(val_pred, y_val)
        val_loss_history.append(val_loss)

        last_val_pred = val_pred

        # Check for improvement in validation loss
        if val_loss < best_val_loss:
            best_val_loss = val_loss
            patience_counter = 0  # Reset patience counter
        else:
            patience_counter += 1  # Increment patience counter


        # Early stopping
        if patience_counter >= patience:
            print(f"Early stopping at epoch {epoch}. Validation loss: {val_loss}, did not improve for {patience} epochs.")
            print(f"Final Train Loss: {avg_train_loss}, Final Validation Loss: {val_loss}")
            break

        # Learning rate decay every 1000 epochs
        if epoch % 1000 == 0:
            learning_rate *= 0.9

        if print_loss and epoch % 1000 == 0:
            print(f"Epoch {epoch}, Train Loss: {avg_train_loss}, Validation Loss: {val_loss}")

    return train_loss_history, val_loss_history, last_val_pred

