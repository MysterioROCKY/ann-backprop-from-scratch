def calculate_mape(y_true, y_pred, epsilon=0.001, threshold=0.1):
    # Create a mask for values greater than the threshold
    mask = np.abs(y_true) > threshold
    # Calculate MAPE only for values where y_true is greater than the threshold
    mape = np.mean(np.abs((y_true[mask] - y_pred[mask]) / (y_true[mask] + epsilon))) * 100
    return mape

