"""### 1.2 Building our ANN class from scratch
1. Basic ANN: Implements a simple Artificial Neural Network with one hidden layer.
2. Flexible Activation: Supports various activation functions like relu, sigmoid, tanh, and linear.
3. Layer-wise Structure: Organizes layers with input sizes, output sizes, and activation functions.
4. Parameter Initialization: Uses appropriate initialization methods (He or Xavier) based on activation functions.
5. Forward and Backward Propagation: Efficiently calculates activations and gradients through the network.
6. Loss Calculation: Computes the mean squared error (MSE) loss between predicted and true outputs.
7. Parameter Update: Modifies weights and biases using gradients and a learning rate.
8. Training and Prediction: Provides methods for training the network on data and making predictions on new inputs.
"""

class ANN_1:
    def __init__(self):
        self.layers = []
        self.params = {}
        self.cache = {}
        self.grads = {}

    def add_layer(self, input_size, output_size, activation='relu'):
        layer_num = len(self.layers) + 1

        if activation == 'relu':
            # He Initialization
            std = np.sqrt(2. / input_size)
        elif activation in ['sigmoid', 'tanh']:
            # Xavier Initialization
            std = np.sqrt(1. / input_size)
        elif activation == 'linear':
            std = np.sqrt(1. / input_size)  # Similar to Xavier
        else:
            raise Exception(f"Unsupported activation: {activation}")

        self.params[f'W{layer_num}'] = np.random.randn(output_size, input_size) * std
        self.params[f'b{layer_num}'] = np.zeros((output_size, 1))
        self.layers.append({
            'input_size': input_size,
            'output_size': output_size,
            'activation': activation
        })

    def relu(self, Z):
        return np.maximum(0, Z)

    def relu_derivative(self, Z):
        return (Z > 0).astype(float)

    def sigmoid(self, Z):
        return 1 / (1 + np.exp(-Z))

    def sigmoid_derivative(self, Z):
        sig = self.sigmoid(Z)
        return sig * (1 - sig)

    def tanh(self, Z):
      return np.tanh(Z)

    def tanh_derivative(self, Z):
      return 1 - np.tanh(Z) ** 2

    def forward(self, X):
        A = X
        self.cache['A0'] = X

        for i, layer in enumerate(self.layers):
            layer_num = i + 1
            W = self.params[f'W{layer_num}']
            b = self.params[f'b{layer_num}']
            Z = np.dot(W, A) + b
            self.cache[f'Z{layer_num}'] = Z

            if layer['activation'] == 'relu':
                A = self.relu(Z)
            elif layer['activation'] == 'sigmoid':
                A = self.sigmoid(Z)
            elif layer['activation'] == 'linear':
                A = Z
            elif layer['activation'] == 'tanh':
                A = self.tanh(Z)
            else:
                raise Exception(f"Unsupported activation: {layer['activation']}")

            self.cache[f'A{layer_num}'] = A

        return A

    def compute_loss(self, Y_pred, Y_true):
        m = Y_true.shape[1]
        loss = (1 / (2 * m)) * np.sum((Y_pred - Y_true) ** 2)
        return loss

    def backward(self, Y_true):
        m = Y_true.shape[1]
        L = len(self.layers)
        Y_pred = self.cache[f'A{L}']

        # Initialize the gradient
        dA = Y_pred - Y_true  # Derivative of MSE loss with respect to A_L

        for i in reversed(range(1, L + 1)):
            Z = self.cache[f'Z{i}']
            A_prev = self.cache[f'A{i-1}']
            W = self.params[f'W{i}']

            layer = self.layers[i-1]
            activation = layer['activation']

            if activation == 'relu':
                dZ = dA * self.relu_derivative(Z)
            elif activation == 'sigmoid':
                dZ = dA * self.sigmoid_derivative(Z)
            elif activation == 'linear':
                dZ = dA  # Derivative of linear activation is 1
            elif activation == 'tanh':
                dZ = dA * self.tanh_derivative(Z)
            else:
                raise Exception(f"Unsupported activation: {activation}")

            dW = (1 / m) * np.dot(dZ, A_prev.T)
            db = (1 / m) * np.sum(dZ, axis=1, keepdims=True)
            dA = np.dot(W.T, dZ)

            self.grads[f'dW{i}'] = dW
            self.grads[f'db{i}'] = db

    def update_parameters(self, learning_rate=0.01):
        L = len(self.layers)
        for i in range(1, L + 1):
            self.params[f'W{i}'] -= learning_rate * self.grads[f'dW{i}']
            self.params[f'b{i}'] -= learning_rate * self.grads[f'db{i}']

    def train(self, X, Y, epochs=10000, learning_rate=0.01, print_loss=True):
        loss_history = []
        for epoch in range(1, epochs + 1):
            Y_pred = self.forward(X)
            loss = self.compute_loss(Y_pred, Y)
            loss_history.append(loss)

            self.backward(Y)
            self.update_parameters(learning_rate)

            if epoch % 1000 == 0:
                learning_rate *= 0.9

            if print_loss and epoch % 1000 == 0:
                print(f"Epoch {epoch}, Loss: {loss}")

        return loss_history

    def predict(self, X):
        return self.forward(X)

"""### 1.3 Funtions to create Mini Batches and do batch training"""

def create_mini_batches(X, Y, batch_size):
    # Shuffle the data at the beginning of each epoch
    m = X.shape[1]  # Number of examples
    permutation = np.random.permutation(m)
    X_shuffled = X[:, permutation]
    Y_shuffled = Y[:, permutation]

    mini_batches = []

    # Create mini-batches
    num_complete_batches = m // batch_size
    for k in range(num_complete_batches):
        X_mini_batch = X_shuffled[:, k * batch_size:(k + 1) * batch_size]
        Y_mini_batch = Y_shuffled[:, k * batch_size:(k + 1) * batch_size]
        mini_batches.append((X_mini_batch, Y_mini_batch))

    # Handle the remaining examples if any
    if m % batch_size != 0:
        X_mini_batch = X_shuffled[:, num_complete_batches * batch_size:]
        Y_mini_batch = Y_shuffled[:, num_complete_batches * batch_size:]
        mini_batches.append((X_mini_batch, Y_mini_batch))

    return mini_batches

def train_with_mini_batches(ann, X, Y, epochs=1000, learning_rate=0.01, batch_size = 64 , print_loss=True):

  print(f"\nTraining with batch size: {batch_size}")
  loss_history = []


  for epoch in range(1, epochs + 1):
      # Create mini-batches
      mini_batches = create_mini_batches(X, Y, batch_size)

      epoch_loss = 0

      for mini_batch_X, mini_batch_Y in mini_batches:
          # Forward and backward pass for each mini-batch
          Y_pred = ann.forward(mini_batch_X)
          loss = ann.compute_loss(Y_pred, mini_batch_Y)
          epoch_loss += loss

          ann.backward(mini_batch_Y)
          ann.update_parameters(learning_rate)

      # Store the loss at the end of each epoch
      loss_history.append(epoch_loss / len(mini_batches))


      if epoch % 1000 == 0:
          learning_rate *= 0.9  # Learning rate decay

      if print_loss and epoch % 100 == 0:
          print(f"Epoch {epoch}, Loss: {epoch_loss / len(mini_batches)}")


  return loss_history

